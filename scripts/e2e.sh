#!/usr/bin/env bash
# End-to-end test: the MCP server against a throwaway QuickBuild 16 + SQL Server 2025 stack.
#
# Usage: scripts/e2e.sh [all|up|setup|test|down|status] [--keep] [--rmi]
#
#   all (default)  up -> setup -> test, then down (also on failure, unless --keep)
#   up             build the images and start an isolated compose project: SQL Server,
#                  QuickBuild, two base agents, an HTTPS front (throwaway CA) and the MCP
#                  server in Streamable HTTP mode
#   setup          run the first-run wizard, authorize the first agent (the second stays
#                  unauthorized on purpose), create fixture configurations, a Git repository
#                  and builds (tests/e2e/qb_fixtures.py)
#   test           run the e2e pytest suite (pytest -m e2e) against the running stack
#   down           remove only what this script created: the project's containers, network,
#                  named volumes and state directory (images are kept as build cache)
#   status         show the project's containers
#
#   --keep         (all) leave the stack running after the tests, for debugging
#   --rmi          (all, down) also remove the images built for this project
#                  (never the shared qb-agent-base:latest tag or pulled images)
#
#   E2E_LOG_DIR    if set, `down` first saves the containers' logs to $E2E_LOG_DIR/compose.log
#
# Isolation (override with env vars): compose project E2E_PROJECT=qbe2e, network subnet
# QB_NETWORK_SUBNET=10.221.0.0/16, published on 127.0.0.1 only: QuickBuild E2E_QB_PORT=18810,
# MCP HTTP E2E_MCP_PORT=14012, HTTPS front E2E_TLS_PORT=18843. Harness passwords and the CA are
# generated per stack and kept in .e2e/<project>/ (mode 0700) until `down`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT="${E2E_PROJECT:-qbe2e}"
STATE="$ROOT/.e2e/$PROJECT"
ENV_FILE="$STATE/stack.env"
SUBNET="${QB_NETWORK_SUBNET:-10.221.0.0/16}"
QB_PORT="${E2E_QB_PORT:-18810}"
MCP_PORT="${E2E_MCP_PORT:-14012}"
TLS_PORT="${E2E_TLS_PORT:-18843}"
QB_LOCAL_URL="http://127.0.0.1:${QB_PORT}"
AGENT_PORT=8811

KEEP=0
RMI=0
COMMAND=all
for arg in "$@"; do
    case "$arg" in
        all|up|setup|test|down|status) COMMAND="$arg" ;;
        --keep) KEEP=1 ;;
        --rmi) RMI=1 ;;
        -h|--help) sed -n '2,29p' "$0"; exit 0 ;;
        *) echo "Unknown argument: $arg (see --help)" >&2; exit 2 ;;
    esac
done

log() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# Refuse project names that could address someone's real stack and its volumes.
case "$PROJECT" in
    ""|quickbuild|quickbuild-mcp|quickbuild14|qb) die "refusing E2E_PROJECT='$PROJECT' (reserved for real stacks)" ;;
esac
[[ "$PROJECT" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || die "E2E_PROJECT must match ^[a-z0-9][a-z0-9_-]*$"

compose() {
    docker compose -p "$PROJECT" --env-file "$ENV_FILE" \
        -f "$ROOT/docker-compose.yml" -f "$ROOT/tests/e2e/compose.e2e.yml" "$@"
}

load_env() {
    [[ -f "$ENV_FILE" ]] || die "no stack state at $ENV_FILE (run: scripts/e2e.sh up)"
    set -a
    # shellcheck source=/dev/null
    . "$ENV_FILE"
    set +a
}

random_secret() {
    # Alphanumeric plus a fixed "Aa1" suffix: satisfies SQL Server's complexity policy and needs
    # no quoting in env files.
    printf '%sAa1' "$(openssl rand -hex 12)"
}

write_env_file() {
    mkdir -p "$STATE"
    chmod 700 "$STATE"
    (
        umask 077
        {
            echo "# Generated by scripts/e2e.sh for compose project $PROJECT; removed by 'down'."
            # docker-compose.yml names its volumes ${COMPOSE_PROJECT_NAME:-quickbuild}_*: pin it so
            # the e2e stack can never mount (or clean up) a real stack's volumes.
            echo "COMPOSE_PROJECT_NAME=$PROJECT"
            echo "QB_NETWORK_SUBNET=$SUBNET"
            echo "E2E_QB_PORT=$QB_PORT"
            echo "E2E_MCP_PORT=$MCP_PORT"
            echo "E2E_TLS_PORT=$TLS_PORT"
            echo "E2E_STATE_DIR=$STATE"
            echo "AGENT_BASE_REPLICAS=2"
            echo "MSSQL_SA_PASSWORD=$(random_secret)"
            echo "QB_DB_PASSWORD=$(random_secret)"
            echo "QB_USER=admin"
            echo "QB_PASSWORD=$(random_secret)"
        } > "$ENV_FILE"
    )
}

make_tls() {
    # Throwaway CA + server certificate for the HTTPS front (qb-tls). nginx runs as an
    # unprivileged user in its container, so the certificate files must be world-readable;
    # they live under the 0700 state directory on the host and are deleted by `down`.
    local dir="$STATE/tls"
    mkdir -p "$dir"
    chmod 755 "$dir"
    openssl req -x509 -newkey rsa:2048 -nodes -days 2 -subj "/CN=quickbuild-mcp e2e CA" \
        -keyout "$dir/ca.key" -out "$dir/ca.pem" \
        -addext "basicConstraints=critical,CA:TRUE" \
        -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
    openssl req -newkey rsa:2048 -nodes -subj "/CN=127.0.0.1" \
        -keyout "$dir/server.key" -out "$dir/server.csr" 2>/dev/null
    printf '%s\n' \
        "subjectAltName=IP:127.0.0.1,DNS:localhost,DNS:qb-tls" \
        "basicConstraints=CA:FALSE" \
        "keyUsage=critical,digitalSignature,keyEncipherment" \
        "extendedKeyUsage=serverAuth" \
        "subjectKeyIdentifier=hash" \
        "authorityKeyIdentifier=keyid,issuer" > "$dir/server.ext"
    openssl x509 -req -in "$dir/server.csr" -CA "$dir/ca.pem" -CAkey "$dir/ca.key" \
        -CAcreateserial -days 2 -out "$dir/server.crt" -extfile "$dir/server.ext" 2>/dev/null
    rm -f "$dir/ca.key" "$dir/ca.srl" "$dir/server.csr" "$dir/server.ext"
    chmod 644 "$dir/ca.pem" "$dir/server.crt" "$dir/server.key"
}

project_containers() {
    docker ps -aq --filter "label=com.docker.compose.project=$PROJECT"
}

assert_isolated_volumes() {
    # Every named volume must resolve to "<project>_..." (never e.g. quickbuild_db_data).
    local foreign
    foreign="$(compose config --format json | python3 -I -c '
import json, sys
project = sys.argv[1]
names = [v.get("name", "") for v in json.load(sys.stdin).get("volumes", {}).values()]
print(" ".join(n for n in names if not n.startswith(project + "_")))
' "$PROJECT")"
    [[ -z "$foreign" ]] || die "volumes would not be isolated to project '$PROJECT': $foreign"
}

preflight_up() {
    command -v docker >/dev/null || die "docker is required"
    docker compose version >/dev/null 2>&1 || die "docker compose v2 is required"
    command -v openssl >/dev/null || die "openssl is required"
    command -v python3 >/dev/null || die "python3 is required"
    if [[ -n "$(project_containers)" ]]; then
        die "compose project '$PROJECT' already has containers (scripts/e2e.sh down, or set E2E_PROJECT)"
    fi
    local used
    used="$(docker network ls -q | xargs -r docker network inspect \
        --format '{{range .IPAM.Config}}{{.Subnet}} {{end}}' 2>/dev/null | tr ' ' '\n' | grep -Fx "$SUBNET" || true)"
    [[ -z "$used" ]] || die "subnet $SUBNET is already used by a Docker network (set QB_NETWORK_SUBNET)"
    for port in "$QB_PORT" "$MCP_PORT" "$TLS_PORT"; do
        if ss -ltnH "sport = :$port" 2>/dev/null | grep -q .; then
            die "port $port is already in use (set E2E_QB_PORT / E2E_MCP_PORT / E2E_TLS_PORT)"
        fi
    done
}

qb_rest() {
    # qb_rest METHOD PATH [curl args...] -> body on stdout; fails on HTTP >= 400
    local method="$1" path="$2"
    shift 2
    curl -fsS --max-time 60 -u "${QB_USER}:${QB_PASSWORD}" -H 'Accept: application/json' \
        -X "$method" "${QB_LOCAL_URL}/rest/${path}" "$@"
}

wait_for_http() {
    local url="$1" timeout="$2" elapsed=0
    until curl -fsS -o /dev/null --max-time 10 "$url"; do
        (( elapsed >= timeout )) && die "timed out after ${timeout}s waiting for $url"
        sleep 5
        elapsed=$((elapsed + 5))
    done
}

cmd_up() {
    preflight_up
    log "Preparing state for compose project '$PROJECT' in $STATE"
    write_env_file
    make_tls
    load_env
    assert_isolated_volumes

    log "Building images (qb-agent-base first; the toolchain agents build FROM it)"
    compose build qb-agent-base
    compose build qb-database qb-server mcp-quickbuild-server

    log "Starting SQL Server and QuickBuild"
    compose up -d --wait --wait-timeout 600 qb-database qb-server
    wait_for_http "$QB_LOCAL_URL/" 300

    log "Starting two base agents, the HTTPS front and the MCP server (HTTP transport)"
    compose up -d qb-agent-base qb-tls mcp-quickbuild-server
    log "Stack is up: QuickBuild at $QB_LOCAL_URL, MCP at http://127.0.0.1:${MCP_PORT}/mcp"
}

agent_ip() {
    docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "${PROJECT}-qb-agent-base-$1"
}

authorize_agent() {
    local ip="$1" elapsed=0
    until qb_rest GET "buildagents/active" | grep -q "\"ip\" : \"$ip\""; do
        # The agent shows up as unauthorized once it has contacted the server.
        qb_rest GET "tokens/authorize?ip=${ip}&port=${AGENT_PORT}" >/dev/null 2>&1 || true
        (( elapsed >= 300 )) && die "agent $ip did not come online within 300s"
        sleep 5
        elapsed=$((elapsed + 5))
    done
    echo "Agent $ip:$AGENT_PORT is authorized and online"
}

cmd_setup() {
    load_env
    if qb_rest GET version >/dev/null 2>&1; then
        log "Setup wizard already completed"
    else
        log "Running the QuickBuild first-run setup wizard"
        python3 -I "$ROOT/tests/e2e/qb_setup.py" --url "$QB_LOCAL_URL" \
            --user "$QB_USER" --password "$QB_PASSWORD" \
            --server-url "http://qb-server:8810" --storage-dir /var/lib/quickbuild/storage
        # QuickBuild initializes after the wizard (/starting); REST answers 404 until it is done.
        local elapsed=0
        until qb_rest GET version >/dev/null 2>&1; do
            (( elapsed >= 300 )) && die "REST API not available 300s after the wizard"
            sleep 5
            elapsed=$((elapsed + 5))
        done
    fi
    log "QuickBuild $(qb_rest GET version) is ready"

    log "Authorizing agent 1 (agent 2 stays unauthorized for grid.list_unauthorized)"
    authorize_agent "$(agent_ip 1)"

    log "Creating fixture configurations, Git repository and builds"
    python3 -I "$ROOT/tests/e2e/qb_fixtures.py" --url "$QB_LOCAL_URL" \
        --user "$QB_USER" --password "$QB_PASSWORD" \
        --server-container "$(compose ps -q qb-server)" \
        --unauthorized-agent-ip "$(agent_ip 2)" \
        --out "$STATE/fixtures.json"

    log "Waiting for the MCP server container to report ready"
    wait_for_http "http://127.0.0.1:${MCP_PORT}/ready" 120
}

run_pytest() {
    if command -v uv >/dev/null 2>&1; then
        (cd "$ROOT" && uv run --no-project --with-requirements requirements.txt pytest "$@")
    else
        (cd "$ROOT" && python3 -m pytest "$@")
    fi
}

cmd_test() {
    load_env
    log "Running the e2e test suite"
    E2E_QB_URL="$QB_LOCAL_URL" E2E_STATE_DIR="$STATE" \
        E2E_MCP_URL="http://127.0.0.1:${MCP_PORT}/mcp" E2E_TLS_URL="https://127.0.0.1:${TLS_PORT}" \
        run_pytest -m e2e tests/e2e --no-cov -p no:cacheprovider
}

cmd_down() {
    if [[ ! -f "$ENV_FILE" ]]; then
        # Still allow cleanup of a half-created project; compose only needs some env file.
        mkdir -p "$STATE"
        : > "$ENV_FILE"
    fi
    if [[ -n "${E2E_LOG_DIR:-}" ]]; then
        # CI uploads these when the run fails
        mkdir -p "$E2E_LOG_DIR"
        compose logs --no-color --timestamps > "$E2E_LOG_DIR/compose.log" 2>&1 || true
        echo "Saved container logs to $E2E_LOG_DIR/compose.log"
    fi
    log "Removing compose project '$PROJECT' (containers and network)"
    compose down --remove-orphans --timeout 30

    # Only volumes that compose created for this project carry its project label.
    log "Removing the project's named volumes"
    local volume
    for volume in $(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT"); do
        docker volume rm "$volume" >/dev/null
        echo "removed volume $volume"
    done

    if (( RMI )); then
        log "Removing the images built for this project"
        local service
        for service in qb-database qb-server qb-agent-maven qb-agent-node qb-agent-dotnet mcp-quickbuild-server; do
            if docker image inspect "${PROJECT}-${service}:latest" >/dev/null 2>&1; then
                docker image rm "${PROJECT}-${service}:latest" >/dev/null
                echo "removed image ${PROJECT}-${service}:latest"
            fi
        done
    fi

    rm -rf -- "$STATE"
    rmdir --ignore-fail-on-non-empty -- "$ROOT/.e2e" 2>/dev/null || true
    log "Teardown complete"
}

cmd_status() {
    load_env
    compose ps
}

on_exit() {
    local rc=$?
    trap - EXIT
    cmd_down || rc=1
    exit "$rc"
}

case "$COMMAND" in
    up) cmd_up ;;
    setup) cmd_setup ;;
    test) cmd_test ;;
    down) cmd_down ;;
    status) cmd_status ;;
    all)
        if (( ! KEEP )); then
            trap on_exit EXIT
        fi
        cmd_up
        cmd_setup
        cmd_test
        log "E2E PASSED"
        ;;
esac
